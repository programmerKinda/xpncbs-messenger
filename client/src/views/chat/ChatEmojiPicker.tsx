export default function ChatEmojiPicker({
  onSelect,
  onStickerSelect,
}: {
  onSelect: (emoji: string) => void
  onStickerSelect?: (stickerId: string) => void
}) {
  const [activeTab, setActiveTab] = useState<'emoji' | 'stickers'>('emoji')
  const [activeGroup, setActiveGroup] = useState(emojiGroups[0].id)
  const [search, setSearch] = useState('')
  const [stickerPacks, setStickerPacks] = useState<StickerPack[]>([])
  const [isLoadingStickers, setIsLoadingStickers] = useState(false)
  const [stickerLoadFailed, setStickerLoadFailed] = useState(false)

  useEffect(() => {
    if (activeTab !== 'stickers' || stickerPacks.length > 0 || stickerLoadFailed) return
    let isMounted = true
    setIsLoadingStickers(true)
    void getStickerPacks()
      .then((packs) => {
        if (isMounted) setStickerPacks(packs)
      })
      .catch(() => {
        if (isMounted) setStickerLoadFailed(true)
      })
      .finally(() => {
        if (isMounted) setIsLoadingStickers(false)
      })
    return () => {
      isMounted = false
    }
  }, [activeTab, stickerPacks.length, stickerLoadFailed])

  const normalizedSearch = search.trim().toLocaleLowerCase()
  const matchingGroups = normalizedSearch
    ? emojiGroups
        .map((group) => ({
          ...group,
          items: group.items.filter(([, keywords]) =>
            keywords.toLocaleLowerCase().includes(normalizedSearch)
          ),
        }))
        .filter((group) => group.items.length > 0)
    : emojiGroups.filter((group) => group.id === activeGroup)
  const visibleItems = matchingGroups.flatMap((group) => group.items)
  const visibleStickers = stickerPacks.flatMap((pack) =>
    pack.stickers
      .filter((sticker) =>
        `${pack.name} ${sticker.title}`.toLocaleLowerCase().includes(normalizedSearch),
      )
      .map((sticker) => ({ ...sticker, packName: pack.name })),
  )

  return (
    <section className="chat-emoji-picker" aria-label="Выбор эмодзи">
      <div className="chat-emoji-picker__header">
        <strong>Эмодзи</strong>
        <span>{visibleItems.length}</span>
      </div>
      <nav className="chat-emoji-picker__tabs" aria-label="Тип содержимого">
        <button
          type="button"
          className={activeTab === 'emoji' ? 'is-active' : ''}
          aria-pressed={activeTab === 'emoji'}
          onClick={() => setActiveTab('emoji')}
        >
          <Smile size={17} /> Эмодзи
        </button>
        {onStickerSelect && (
          <button
            type="button"
            className={activeTab === 'stickers' ? 'is-active' : ''}
            aria-pressed={activeTab === 'stickers'}
            onClick={() => setActiveTab('stickers')}
          >
            <Sticker size={17} /> Стикеры
          </button>
        )}
      </nav>
      <label
        className="chat-emoji-picker__search"
        onPointerDown={(event) => event.stopPropagation()}
      >
        <span aria-hidden="true">⌕</span>
        <input
          type="search"
          value={search}
          onChange={(event) => setSearch(event.target.value)}
          placeholder={activeTab === 'emoji' ? 'Поиск эмодзи' : 'Поиск стикеров'}
          aria-label={activeTab === 'emoji' ? 'Поиск эмодзи' : 'Поиск стикеров'}
        />
        {search && (
          <button type="button" onClick={() => setSearch('')} aria-label="Очистить поиск">
            ×
          </button>
        )}
      </label>
      {activeTab === 'emoji' && !normalizedSearch && (
        <nav className="chat-emoji-picker__categories" aria-label="Категории эмодзи">
          {emojiGroups.map((group) => (
            <button
              key={group.id}
              type="button"
              className={activeGroup === group.id ? 'is-active' : ''}
              title={group.label}
              aria-label={group.label}
              aria-pressed={activeGroup === group.id}
              onClick={() => setActiveGroup(group.id)}
            >
              <EmojiGraphic emoji={group.icon} category />
            </button>
          ))}
        </nav>
      )}
      {activeTab === 'emoji' ? (
      <div className="chat-emoji-picker__results" role="list" aria-label="Эмодзи">
        {matchingGroups.length === 0 ? (
          <p className="chat-emoji-picker__empty">Ничего не найдено</p>
        ) : (
          matchingGroups.map((group) => (
            <div className="chat-emoji-picker__group" key={group.id}>
              {normalizedSearch && <h3>{group.label}</h3>}
              <div className="chat-emoji-picker__grid">
                {group.items.map(([emoji, keywords], index) => (
                  <button
                    type="button"
                    key={`${emoji}-${index}`}
                    title={keywords.split(' ').slice(0, 3).join(' ')}
                    aria-label={`${keywords}, ${emoji}`}
                    role="listitem"
                    onClick={() => {
                      onSelect(emoji)
                    }}
                  >
                    <EmojiGraphic emoji={emoji} />
                  </button>
                ))}
              </div>
            </div>
          ))
        )}
      </div>
      ) : (
        <div className="chat-emoji-picker__results" role="list" aria-label="Стикеры">
          {isLoadingStickers ? (
            <p className="chat-emoji-picker__empty">Загрузка стикеров…</p>
          ) : stickerLoadFailed ? (
            <p className="chat-emoji-picker__empty">Не удалось загрузить стикеры</p>
          ) : visibleStickers.length === 0 ? (
            <p className="chat-emoji-picker__empty">Стикеры не найдены</p>
          ) : (
            stickerPacks.map((pack) => {
              const packStickers = visibleStickers.filter((sticker) => sticker.packName === pack.name)
              if (packStickers.length === 0) return null
              return (
                <div className="chat-emoji-picker__group" key={pack.id}>
                  <h3>{pack.name}</h3>
                  <div className="chat-emoji-picker__grid chat-emoji-picker__sticker-grid">
                    {packStickers.map((sticker) => (
                      <button
                        type="button"
                        key={sticker.id}
                        title={sticker.title}
                        aria-label={`Отправить стикер: ${sticker.title}`}
                        role="listitem"
                        onClick={() => {
                          onStickerSelect?.(sticker.id)
                          usePopupStore.getState().onClose()
                        }}
                      >
                        <img src={sticker.url} alt={sticker.title} loading="lazy" />
                      </button>
                    ))}
                  </div>
                </div>
              )
            })
          )}
        </div>
      )}
      <footer className="chat-emoji-picker__footer">
        {activeTab === 'emoji' ? 'Выберите эмодзи' : 'Нажмите на стикер, чтобы отправить'}
      </footer>
    </section>
  )
}
