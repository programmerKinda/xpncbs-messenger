type EmojiItem = readonly [emoji: string, keywords: string]

function EmojiGraphic({ emoji, category = false }: { emoji: string; category?: boolean }) {
  const [imageFailed, setImageFailed] = useState(false)
  const className = category ? 'chat-emoji-picker__category-image' : 'chat-emoji-picker__emoji'

  if (imageFailed) {
    return (
      <span className={className} aria-hidden="true">
        {emoji}
      </span>
    )
  }

  return (
    <img
      className={className}
      src={`/images/emoji/apple/64/${emojiToUnified(emoji)}.png`}
      alt=""
      loading="lazy"
      decoding="async"
      draggable={false}
      onError={() => setImageFailed(true)}
    />
  )
}

